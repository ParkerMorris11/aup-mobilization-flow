export const SAMPLE_AUP_TEXT = `ACME CORPORATION
Artificial Intelligence Acceptable Use Policy
Effective Date: January 1, 2026

1. PURPOSE
This policy establishes guidelines for the safe, responsible, and compliant use of artificial intelligence tools by all Acme Corporation employees, contractors, and partners.

2. APPROVED TOOLS
Employees may only use organization-approved AI tools for business purposes:
- Microsoft Copilot (enterprise license)
- ChatGPT Enterprise (provisioned accounts)
- GitHub Copilot (engineering teams only)

Personal AI accounts (free ChatGPT, personal Claude, Gemini consumer) must not be used for Acme work.

3. DATA RESTRICTIONS
The following data must NEVER be entered into AI tools:
- Customer personally identifiable information (names, emails, phone numbers, addresses)
- Financial data (revenue, invoices, account balances, compensation)
- Protected health information
- Authentication credentials, API keys, or passwords
- Unreleased product roadmaps or acquisition discussions

Employees may use AI to draft templates or structure documents, then add sensitive details manually outside the AI tool.

4. OUTPUT REVIEW
All AI-generated content used externally (customer emails, marketing, legal documents, code committed to production) must be reviewed by a human before use. AI output is a draft, not a final deliverable.

5. DISCLOSURE
When AI materially contributes to customer-facing deliverables, employees must disclose AI assistance per the Communications team guidelines. Internal brainstorming does not require disclosure.

6. HR & PEOPLE DATA
Performance reviews, disciplinary records, hiring decisions, and employee personal information require written approval from HR before any AI processing.

7. INTELLECTUAL PROPERTY
Source code, proprietary algorithms, and trade secrets may only be processed in approved development environments with data-loss prevention controls. Do not paste proprietary code into unapproved tools.

8. ESCALATION
When uncertain, contact IT Security (security@acme.com) or your manager before proceeding. Policy exceptions require written approval from the Chief Information Security Officer.

9. ACKNOWLEDGMENT
All employees must complete AI safety training and acknowledge this policy annually.`;

